import test from 'node:test';
import assert from 'node:assert/strict';
const store=new Map();
globalThis.localStorage={getItem:key=>store.has(key)?store.get(key):null,setItem:(key,v)=>store.set(key,String(v)),removeItem:key=>store.delete(key),key:i=>[...store.keys()][i],get length(){return store.size}};
import {renderHome} from '../src/pages/home.js';
import {renderExplore} from '../src/pages/explore.js';
import {renderSports} from '../src/pages/sports.js';
import {renderEvents} from '../src/pages/events.js';
import {renderCommunity} from '../src/pages/community.js';
